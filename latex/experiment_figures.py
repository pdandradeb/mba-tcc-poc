"""Generate scientific plots with PGFPlots, already used by the thesis template."""


def latency_figure(boxes):
    plots=[]
    for position, box in enumerate(boxes.values(), 1):
        spec=','.join(f'{key}={box[field]:.12g}' for key,field in [
            ('lower whisker','lower_whisker'),('lower quartile','q1'),('median','median'),
            ('upper quartile','q3'),('upper whisker','upper_whisker')])
        coords=' '.join(f'(0,{value:.12g})' for value in box['outliers'])
        plots.append(r'\addplot+[draw=black,fill=blue!12,mark=*,mark size=1pt,mark options={draw=black,fill=black},boxplot prepared={'
                     +spec+f',draw position={position}'+r'}] coordinates {'+coords+'};')
    return r'''% Generated by generate_experiment_tables.py.
\begin{figure}[htbp]
\centering
\caption{Distribuição da latência dos 100 casos de cada método}
\label{fig:latencias_distribuicao}
\begin{tikzpicture}
\begin{axis}[
    width=13.5cm,height=7cm,boxplot/draw direction=y,
    ymode=log,log basis y=10,ymin=0.00007,ymax=230,
    ylabel={Latência em segundos (escala logarítmica)},
    xtick={1,2,3,4},xticklabels={Método 1,Método 2,Método 3,Método 4},
    xmin=0.4,xmax=4.6,ymajorgrids=true,grid style={gray!25},
    tick label style={font=\small},label style={font=\small}]
'''+ '\n'.join(plots)+r'''
\end{axis}
\end{tikzpicture}
\fonte{Cálculos próprios nos registros da rodada, incluindo os bloqueios. Caixas entre os percentis 25 e 75, linha na mediana e hastes nos valores observados até 1,5 amplitude interquartil. Pontos além das hastes são mantidos. Quartis com interpolação linear na posição $(n-1)p$.}
\end{figure}
'''


def adequacy_figure(intervals):
    pieces=[]
    for key,offset,color,mark in [('adequacy_among_delivered',-0.14,'blue!65!black','*'),
                                  ('adequate_delivery',0.14,'black!65','triangle*')]:
        coords=[]
        for i,method in enumerate(intervals,1):
            v=intervals[method][key]
            x=100*v['proportion']; low,high=[100*z for z in v['wilson95']]
            coords.append(f'({x:.9g},{i+offset:.3f}) += ({high-x:.9g},0) -= ({x-low:.9g},0)')
        pieces.append(r'\addplot+[only marks,mark='+mark+',color='+color+',mark options={draw='+color+',fill='+color+'}'+
                      r',error bars/.cd,x dir=both,x explicit,error mark options={rotate=90,mark size=2.5pt}] coordinates {'+
                      ' '.join(coords)+'};')
    for i,method in enumerate(intervals,1):
        for key,offset in [('adequacy_among_delivered',-0.14),('adequate_delivery',0.14)]:
            v=intervals[method][key]
            pieces.append(r'\node[anchor=west,font=\scriptsize] at (axis cs:102,'+f'{i+offset:.3f}'+') {'+f"{v['successes']}/{v['denominator']}"+'};')
    return r'''% Generated by generate_human_review_tables.py.
\begin{figure}[htbp]
\centering
\caption{Adequação entre entregas e disponibilidade de respostas adequadas}
\label{fig:adequacao_disponibilidade}
\begin{tikzpicture}
\begin{axis}[
    width=12.5cm,height=6.7cm,xmin=0,xmax=100,ymin=0.5,ymax=4.5,y dir=reverse,
    xlabel={Proporção (\%) e intervalo de Wilson a 95\%},
    ytick={1,2,3,4},yticklabels={Método 1,Método 2,Método 3,Método 4},
    xmajorgrids=true,grid style={gray!25},clip=false,
    tick label style={font=\small},label style={font=\small},
    legend style={at={(0.5,1.16)},anchor=south,draw=none,font=\small,column sep=8pt},legend columns=2]
'''+ '\n'.join(pieces)+r'''
\legend{Entre entregas,Por pergunta}
\end{axis}
\end{tikzpicture}
\fonte{Julgamentos globais realizados pelo autor. À direita constam numerador e denominador de cada medida. Os intervalos descrevem proporções individuais e não testam diferenças entre métodos.}
\end{figure}
'''
